#pragma once
#include "Core/Types.hpp"

namespace Smp {

// Цвет ноты по её инструменту (волне) — ОДНА таблица на все виды (16 каналов
// и сетка «клавиши» рисуют одну и ту же ленту; расхождение цветов между
// двумя проекциями одной ноты было бы ложью в отрисовке).
inline const s32* WaveColor(u32 wave) {
    static const s32 rgb[4][3] = {
        { 205, 85, 95 },    // пила
        { 95, 115, 215 },   // квадрат
        { 95, 195, 115 },   // треугольник
        { 225, 195, 95 },   // синус
    };
    return rgb[wave & 3];
}

}  // namespace Smp
