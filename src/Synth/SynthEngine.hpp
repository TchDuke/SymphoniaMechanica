#pragma once
#include "Core/Types.hpp"
#include <atomic>

// Движок синтеза SymphoniaMechanica: пул голосов, осцилляторы, огибающая.
//
// Это доменная логика синтезатора — то, чего нет в Libs: Libs/Audio даёт
// микшер, устройство и записи, а формы звука, огибающую и политику
// вытеснения голосов определяет сам инструмент. Поэтому движок живёт в
// приложении, а не в библиотеке.
//
// Чисто DSP: без потоков, без устройств. Ввод — события нот и огибающая
// (LUT, безблокировочная замена), вывод — набор моно-отсчётов. Живой звуковой
// поток и запись поверх этого — AudioBus.
//
// ДВА СВОЙСТВА ЗВУКА, задуманное, а не случайное:
//   КОГЕРЕНТНОСТЬ: фаза осциллятора живёт в Канале (ноте), а не в голосе —
//     разрыв ноты (NoteOff) не обнуляет осциллятор, и перебитые ноты одной
//     высоты складываются, а не «рестартовятся» в хаос.
//   ОБВОЛОЧКА: кусочно-линейный LUT на фиксированное окно (kEnvWindow с) —
//     форма звука инструмента, а не хардкод ADSR. После окна — удержание
//     последней ступени; после NoteOff — короткий хвост до нуля.

namespace Smp {

class SynthEngine {
public:
    // Формы волн — свой набор синтезатора (Libs/Audio::Wave — для beep/шума).
    enum WaveKind : u32 { WaveSaw = 0, WaveSquare, WaveTriangle, WaveSine, WaveCount };

    static const char* WaveName(WaveKind w);

    // Голосов в пуле: для v1 — 16 (обычный минимум полифонии).
    enum { kVoices = 16 };

    // Огибающая: LUT на kEnvLut ступеней, развёрнутый на окно kEnvWindow секунд.
    enum { kEnvLut = 2048 };
    static const f32 kEnvWindow;   // 2.0 с

    void Init(s32 sampleRate);

    // Включить ноту (MIDI 0..127). Повторный NoteOn той же ноты — RETRIGGER:
    // огибающая стартует с начала окна, но голос не плодится (фаза — с места,
    // на котором канал её оставил).
    void NoteOn(s32 midi, s32 velocity, WaveKind wave);
    void NoteOff(s32 midi);

    // Огибающая из ГОТОВОГО LUT (kEnvLut значений, 0..1). Замена
    // безблокировочная (пинг-понг): UI-поток кладёт новую таблицу, звуковой —
    // всегда читает цельную; нота, уже идущая, доживёт по старой до конца окна.
    // Вызывать можно из любого потока ДО или ВО ВРЕМЯ работы.
    void SetEnvelope(const f32* lut);

    // Сумма активных голосов в out[n] (mono, Real, уже умноженная на master),
    // с обрезкой в [-1, 1].
    void Render(Real* out, s32 frames, Real master);

    s32 ActiveVoices() const;
    // Миди-номера активных голосов (до kVoices), для подсветки клавиатуры.
    void ActiveNotes(s32* out) const;

private:
    struct Voice {
        bool  active = false;
        s32   midi = -1;
        u32   wave = 0;
        f32   phase = 0.0f;
        f32   phaseInc = 0.0f;
        f32   envPos = 0.0f;   // положение по LUT [0..1]
        f32   level = 0.0f;    // текущий уровень огибающей [0..1]
        f32   vel = 0.75f;     // доля громкости, от velocity
        bool  releasing = false;
        u32   age = 0;
    };

    Real osc(f32 phase, u32 wave) const;
    Voice* findNote(s32 midi);

    Voice  m_v[kVoices];
    f32    m_env[2][kEnvLut] = {};   // пинг-понг: две таблицы, одна читается
    std::atomic<u32> m_envSel{0};    // индекс читаемой (0/1)
    f32    m_envStep = 0;            // шаг LUT на отсчёт
    f32    m_relRate = 0;            // хвост после NoteOff: падение уровня за отсчёт
    f32    m_chanPhase[128] = {};    // фаза КАНАЛА (ноты) — переживает голос
    s32    m_rate = 0;
    // Мягкий ограничитель суммы голосов (Render): ниже колена — единичный
    // пропуск, выше — плавный сгиб к потолку. По одиночной ноте (пик 0,79
    // при vel 100) колено не трогает; под многоканалом (сумма > 1 по
    // построению) вместо жёсткого клиппинга — сжатие без угла, а угол —
    // те самые «искажения», что слышатся на аккорде.
    static const f32 kLimKnee;   // колено мягкого ограничителя (значение — в cpp)
    static f32 kSineTab[2048];  // таблица синуса (Init заполняет её, до этого ноль)
};

}  // namespace Smp
