#pragma once
#include "Core/Types.hpp"

#include <mutex>

// Временная лента SymphoniaMechanica: 36 дорожек (по одной на клавишу
// C2..B4), ось времени в долях.
//
// Это та же доменная логика, что и движок: чистые данные + расписание, без
// потока и без устройств (поток и микшер — AudioBus). UI-поток вставляет
// ноты и ведёт транспорт, звуковой поток раз в такт спрашивает: «что
// наступило за эти доли?» — и получает список выстрелов, который сам и
// исполняет (ноты — в движок, щелчки метронома — в микшер).
//
// Модель — как у Audio::Midi: время события в долях от начала. Отличие от .mid:
// дорожка — не имя исполнителя, а СТРОКА ленты (0..35), и инструмент ноты
// помечен самой нотой — ленте равно, чем она звучит. Вид «16 каналов» —
// просто первые 16 строк этой же ленты: одна лента, две проекции.

namespace Smp {

class Timeline {
public:
    struct Note {
        bool  used = false;   // слот занят
        s32   row = 0;        // дорожка 0..kRows-1
        s32   beat = 0;       // доля начала (целая: вставка по сетке)
        s32   midi = 0;       // нота 0..127
        u32   wave = 0;       // инструмент (WaveKind движка)
        s32   dur = 1;        // длительность, доли
        bool  staccato = false; // Ctrl-клетка: короткая нота со своей паузой
    };

    // Выстрел, исполнить которого должен AudioBus (он один видит движок и микшер).
    struct Fired {
        s32 kind = 0;   // 0 нота вкл 1 нота выкл 2 щелчок 3 щелчок-акцент
        s32 midi = -1;
        u32 wave = 0;
        s32 beat = 0;    // доля границы события (порядок исполнения — по ней)
        s32 chunks = 0;  // отложить исполнение на N рендер-тактов (0 — сразу)
    };

    static const s32 kRows    = 36;   // полос ленты: одна на клавишу C2..B4
    static const s32 kBeats   = 64;   // длина окна, долей (16 тактов 4/4)
    // Потолок событий — ВСЯ СЕТКА (36 × 64): сетка в виде «клавиш» никогда
    // не отвечает «нет» на клетку.
    static const s32 kMaxNote = kRows * kBeats;

    // Дорожка ↔ клавиша: строка 0 = До2 (НЧ, внизу вида), 35 = Си4 (вверху).
    static s32 RowMidi(s32 row) { return kFirstMidi + row; }
    static s32 MidiRow(s32 midi) {
        if(midi < kFirstMidi || midi >= kFirstMidi + kRows) return -1;
        return midi - kFirstMidi;
    }
    static const s32 kFirstMidi = 36;   // До2 — та же палитра, что у клавиатуры

    // Стаккато-нота живёт kStaccatoChunks рендер-тактов (≈ 3 · 42,7 мс
    // = 128 мс); остаток доли — пауза.
    static const s32 kStaccatoChunks = 3;

    // ── UI-поток ─────────────────────────────────────────────────────────
    // Вставить ноту. Та же (дорожка, доля, нота) — замена инструмента,
    // не копирование. Клетка, занятая чужим штрихом (нота короче своей
    // клетки), вторую ноту не берёт — молча мимо. Лента полная — так же.
    // staccato (Ctrl-клетка): короткая нота со своей паузой в доле; без
    // него — обычная клетка, звучит слитно с соседними клетками той же
    // дорожки (legato: без разрыва на границе).
    bool Insert(s32 row, s32 beat, s32 midi, u32 wave, bool staccato = false);
    // Снять ноту. Нет её — вернула false (ничего не сломалось).
    bool Remove(s32 row, s32 beat, s32 midi);
    bool Has(s32 row, s32 beat, s32 midi) const;
    // Клетка занята — сама нотой ИЛИ частью штриха (нотой, чья длительность
    // её покрывает). Has — только на доле начала ноты.
    bool HasAny(s32 row, s32 beat, s32 midi) const;
    // Штрих: отрезок [lo..hi] включительно — ОДНА сплошная нота
    // (dur = hi−lo+1): в проигрывании звук не рвётся (один «вкл» в начале,
    // один «выкл» в конце), в сетке рисуется одним горизонтальным
    // прямоугольником. Стоявшие внутри ноты заменяются штрихом, перерезавшие
    // границы — укорачиваются (хвост за правой границей живёт).
    bool Paint(s32 row, s32 lo, s32 hi, s32 midi, u32 wave);
    // Снять ОДНУ клетку: одиночная нота снимается целиком, штрих надвое
    // (клетка становится паузой, обе половины живут).
    bool RemoveCell(s32 row, s32 beat, s32 midi);
    void Clear();
    s32  NoteCount() const;
    // Снять список нот для отрисовки (копия: лента может измениться в любой миг).
    s32  CopyNotes(Note* dst, s32 maxNotes) const;

    // Транспорт: по умолчанию ВЫКЛ (прослушивание — только по явному пуску).
    void Play();               // с доли 0
    void Stop();               // плавный: выстрелы «выкл» допишет звуковой поток
    bool Playing() const;
    f32  PosBeats() const;     // позиция плейхеда — для отрисовки

    // Метроном: настраиваемый генератор такта. Темп — доли в минуту; пока
    // выключен, сетку ленту рисует, а щелкать не щелкает.
    void SetBpm(f32 bpm);      // 30..240
    f32  Bpm() const;
    void SetMetro(bool on);
    bool Metro() const;

    // ── Звуковой поток: один раз за рендер-такт ──────────────────────────
    // Продвинуть плейхед на dtBeats (AudioBus считает их из фреймов и темпа)
    // и отдать выстрелы, наступившие на пройденном отрезке. Конец окна —
    // самоостановка. Возвращает число выстрелов.
    s32 Step(f32 dtBeats, Fired* out, s32 maxOut);

private:
    // Плавный стоп и выстрелы — под тем же замком, что и Step (одна
    // функция, не два пути в одни данные).
    s32 stepLocked(f32 dtBeats, Fired* out, s32 maxOut);
    // Индекс ноты (дорожка, доля, нота) под занятым замком; -1 — нет такой.
    s32 findLocked(s32 row, s32 beat, s32 midi) const;
    // Индекс ноты (дорожка, нота), чья длительность ПОКРЫВАЕТ долю; -1 — нет.
    s32 coverLocked(s32 row, s32 beat, s32 midi) const;

    Note               m_note[kMaxNote];
    s32                m_count = 0;

    bool               m_playing = false;
    f32                m_pos = 0.0f;
    bool               m_stopPending = false;

    f32                m_bpm = 120.0f;
    bool               m_metro = true;

    mutable std::mutex m_mu;
};

}  // namespace Smp
